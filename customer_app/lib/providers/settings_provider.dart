import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

String _currentLocale = 'ar';

class SettingsProvider extends ChangeNotifier {
  static const _key = 'locale';
  String _locale = 'ar';

  String get locale => _locale;

  bool get isArabic => _locale == 'ar';

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    _locale = prefs.getString(_key) ?? 'ar';
    _currentLocale = _locale;
    notifyListeners();
  }

  Future<void> setLocale(String locale) async {
    if (locale != 'ar' && locale != 'en') return;
    _locale = locale;
    _currentLocale = locale;
    notifyListeners();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_key, locale);
  }

  String t(String key) => L10n.t(key);
}

class L10n {
  static const Map<String, Map<String, String>> _strings = {
    'ar': _ar,
    'en': _en,
  };

  /// Current locale for global (model-level) translations.
  static String get locale => _currentLocale;

  /// Translate [key] using the current app language; falls back to Arabic.
  static String t(String key) => _strings[_currentLocale]?[key] ?? _ar[key] ?? key;

  /// Translate [key] for an explicit [locale].
  static String translate(String locale, String key) =>
      _strings[locale]?[key] ?? _ar[key] ?? key;

  /// Translate [key] then substitute `{placeholder}` tokens with [args].
  static String f(String key, [Map<String, String> args = const {}]) {
    var s = t(key);
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
}

